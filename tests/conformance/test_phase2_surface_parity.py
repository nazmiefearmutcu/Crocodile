def _served() -> dict[str, dict[str, set[str]]]:
    """Surface kind → capability name → every parameter it accepts, from wherever it is served.

    Two sources, unioned, both optional. The legacy files answer for their own kind today.
    The registry answers for all three kinds, because a projection is derived from it
    mechanically — a name in :data:`REGISTRY` is a command, a route *and* a tool by
    construction, which is the whole premise of Phase 2. Neither source has to exist, so the
    same assertions hold on both sides of the deletion without this file changing.

    Kept per kind rather than pooled: with one pool, deleting the `funding-apr` command would
    stay green on the strength of `GET /api/v1/funding-apr`, and losing a command is losing a
    command. The cost is that a capability already in the registry is *trusted* to be
    projected onto all three surfaces rather than measured — two capabilities today. That
    trust is the projection's own tests to keep, not this gate's; what this gate owns is that
    nothing which was on the wire before Phase 2 falls out of both sources at once.
    """
    served: dict[str, dict[str, set[str]]] = {kind: {} for kind in _SCANNERS}

    def add(kind: str, name: str, params: Iterable[str]) -> None:
        served[kind].setdefault(name, set()).update(_canonical_param(name, p) for p in params)

    for (_fork, kind), path in _LEGACY.items():
        if not path.exists():
            continue
        for raw, body in _SCANNERS[kind](path).items():
            name = _canonical_name(kind, raw)
            add(kind, name, body["options"] if "options" in body else body["params"])

    try:
        from crocodile.core.capability import REGISTRY
    except Exception:  # pragma: no cover - the registry is not optional in practice
        return served

    for capability in REGISTRY.values():
        for spelling in (capability.name, *capability.aliases):
            for surface in _SCANNERS:
                add(
                    surface,
                    _canonical_name("cli", spelling),
                    capability.params.__struct_fields__,
                )
    return served


def _frozen() -> dict[str, dict[str, dict[str, Any]]]:
    raw = json.loads(_FIXTURE.read_text())
    return {fork: kinds for fork, kinds in raw.items() if not fork.startswith("_")}


def _frozen_entries() -> list[tuple[str, str, str, str, dict[str, Any]]]:
    """(fork, kind, raw name, canonical name, parameters) for every frozen entry."""
    return [
        (
            fork,
            kind,
            raw,
            _canonical_name(kind, raw),
            body["options"] if "options" in body else body["params"],
        )
        for fork, kinds in _frozen().items()
        for kind, entries in kinds.items()
        for raw, body in entries.items()
    ]


