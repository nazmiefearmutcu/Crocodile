def test_the_infrastructure_list_is_not_hoarding_entries() -> None:
    """An exemption list is where losses go to be forgotten unless it is kept honest.

    Three ways an entry stops being true: it names something the surfaces never exposed, it
    carries no argument, or the thing it calls infrastructure has since been declared a
    capability. All three mean the entry has to go rather than sit there excusing a name
    nobody is checking.
    """
    frozen_names = {name for *_, name, _params in _frozen_entries()}
    stale = sorted(name for name in _INFRASTRUCTURE if name not in frozen_names)
    assert not stale, f"_INFRASTRUCTURE entries that describe nothing the six surfaces had: {stale}"

    unargued = sorted(name for name, why in _INFRASTRUCTURE.items() if not why.strip())
    assert not unargued, f"_INFRASTRUCTURE entries with no argument: {unargued}"

    from crocodile.core.capability import REGISTRY

    contradicted = sorted(
        name
        for name in _INFRASTRUCTURE
        if name in REGISTRY or any(name in c.aliases for c in REGISTRY.values())
    )
    assert not contradicted, (
        f"these are declared capabilities and cannot also be infrastructure: {contradicted}"
    )


def test_the_infrastructure_list_cannot_grow_to_excuse_a_deleted_capability() -> None:
    """A name that served a capability yesterday cannot become one that never was.

    The hole an exit review walked through, end to end: delete the ``catalog-dates``
    declaration, add ``catalog-dates`` and ``list-dates`` to :data:`_INFRASTRUCTURE`, and
    the whole conformance suite passes. Every gate that could have caught it declined for a
    different reason, and each reason was correct in isolation:

    * Gate 4 compares the three surfaces against ``REGISTRY``, so a capability that leaves
      the registry leaves all three surfaces together and the comparison stays balanced.
    * Gate 2 iterates ``REGISTRY``, so a name that is no longer in it is no longer its
      subject.
    * :func:`test_no_wire_name_disappeared` was satisfied by the new ledger entry — and its
      own failure message recommended exactly that.
    * :func:`test_the_infrastructure_list_is_not_hoarding_entries` asks that the name was on
      the frozen wire, that it carries prose, and that it is **not currently registered**.
      A just-deleted capability satisfies all three by construction; the third is the one
      that inverts, because deletion is what makes it true.

    What none of them could ask is the question this list actually answers, which is about
    the past rather than about today. So the answer is pinned in
    :data:`_INFRASTRUCTURE_AS_SHIPPED` and an addition has to survive being named there.
    """
    added = sorted(set(_INFRASTRUCTURE) - _INFRASTRUCTURE_AS_SHIPPED)
    assert not added, (
        f"_INFRASTRUCTURE grew by {added}. This list means *never a capability*. If one of "
        "these was serving a capability that has since been deleted, the deletion is the "
        "thing to justify — not the name — and it is not justifiable here: restore the "
        "declaration, or serve the name through `aliases`. If it genuinely was never a "
        "capability, add it to _INFRASTRUCTURE_AS_SHIPPED in the same commit, where the "
        "diff shows a reviewer both halves of the claim at once."
    )

    from crocodile.core.capability import REGISTRY

    dropped = sorted(
        name
        for name in _INFRASTRUCTURE_AS_SHIPPED
        if name not in _INFRASTRUCTURE
        and name not in REGISTRY
        and not any(name in cap.aliases for cap in REGISTRY.values())
    )
    assert not dropped, (
        f"{dropped} left _INFRASTRUCTURE without becoming capabilities. The one exit this "
        "list has is being declared — which is what "
        "test_the_infrastructure_list_is_not_hoarding_entries forces — so a name that is on "
        "neither list is a wire name with nothing left saying what happened to it."
    )


def test_the_rename_ledger_is_not_hoarding_entries() -> None:
    """Every rename must still describe two spellings of something that existed.

    A ledger entry whose source name was never on the wire is not recording a decision; it is
    widening the gate for free. Both ends are checked: the losing spelling has to be one the
    six surfaces really exposed, and the winning one has to be somewhere a caller can reach.
    """
    from crocodile.core.capability import REGISTRY

    frozen = _frozen_entries()
    mechanical = {_mechanical_name(kind, raw) for _fork, kind, raw, _name, _params in frozen}
    canonical = {name for *_, name, _params in frozen} | set(REGISTRY)
    stale: list[str] = []

    for source, (target, why) in _NAME_RENAMES.items():
        entry = f"_NAME_RENAMES[{source!r}]"
        if source not in mechanical:
            stale.append(f"{entry}: no surface ever exposed that spelling")
        if target not in canonical:
            stale.append(f"{entry} → {target}: nothing of that name is reachable")
        assert why.strip(), f"the rename of {source} carries no justification"

    frozen_params = {
        (name, param.lstrip("-").lower().replace("-", "_"))
        for *_, name, params in frozen
        for param in params
    }
    reachable_params = {param for _name, param in frozen_params} | {
        field for capability in REGISTRY.values() for field in capability.params.__struct_fields__
    }
    for (capability_name, param), (target, why) in _PARAM_RENAMES.items():
        entry = f"_PARAM_RENAMES[{capability_name!r}, {param!r}]"
        if capability_name is None:
            if not any(p == param for _n, p in frozen_params):
                stale.append(f"{entry}: no surface ever accepted that parameter")
        elif (capability_name, param) not in frozen_params:
            stale.append(f"{entry}: {capability_name} never accepted that parameter")
        if target not in reachable_params:
            stale.append(f"{entry} → {target}: nothing of that name is accepted anywhere")
        assert why.strip(), f"the rename of {param} carries no justification"

    for param, why in _AMBIENT_PARAMETERS.items():
        if not any(p == param for _n, p in frozen_params):
            stale.append(f"_AMBIENT_PARAMETERS[{param!r}]: no surface ever accepted it")
        assert why.strip(), f"the ambient parameter {param} carries no justification"

    assert not stale, f"exemption entries that no longer describe anything: {stale}"
