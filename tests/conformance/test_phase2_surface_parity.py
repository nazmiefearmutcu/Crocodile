def _mechanical_name(kind: str, raw: str) -> str:
    """The wire name with only its surface's own decoration removed.

    A REST entry loses its method and version prefix because ``Capability.name`` *is* the
    path segment — that is the documented projection rule, not a guess about what a route
    might have meant. Nothing else is inferred here: stripping MCP's ``get_`` habit
    mechanically would silently equate names that were never the same capability, so those
    go through :data:`_NAME_RENAMES` one argued entry at a time.
    """
    if kind == "rest":
        path = raw.split(" ", 1)[1]
        path = path.removeprefix("/api/v1/").removeprefix("/api/")
        path = re.sub(r"\{[^}]*\}", "", path).strip("/")
        raw = path.replace("/", "-") or "/"
    return raw.strip().lower().replace("_", "-")


def _canonical_name(kind: str, raw: str) -> str:
    """The one capability a wire entry names, after the rename ledger is consulted."""
    name = _mechanical_name(kind, raw)
    return _NAME_RENAMES.get(name, (name, ""))[0]


def _canonical_param(capability: str, raw: str) -> str:
    param = raw.lstrip("-").strip().lower().replace("-", "_")
    for key in ((capability, param), (None, param)):
        if key in _PARAM_RENAMES:
            return _PARAM_RENAMES[key][0]
    return param


