"""No wire name may disappear when the six legacy surfaces are deleted.

Phase 2 collapses ``crypto/legacy/{cli,api_server,mcp_server}.py`` and their equity
counterparts — 15 873 lines writing one capability list out six times — into three thin
projections over :data:`crocodile.core.capability.REGISTRY`. That is the largest deletion
in the project, and it rests on the same claim Phase 1 made about seven shared modules:
that the survivor covers everything the deleted copy did. Phase 1 was wrong seven times
and nothing raised; the queries just came back empty.

``premerge_public_api.json`` measures that claim for Python identifiers. It says nothing
about what a *user* can call. A CLI command, a REST path and an MCP tool name are the
product's actual contract, and every one of them is about to be regenerated by a
projector, so ``premerge_phase2_surface.json`` freezes them while all six surfaces are
still intact — the same discipline, applied to the wire.

Two properties make this gate worth having rather than merely present:

**It does not care how a name is served.** Resolution is against a union of sources — the
legacy files today, the capability registry after the port — so the same assertions hold
across the deletion without the test changing. It is also fork-agnostic: whether a name is
answered for crypto, for equity or for both is the symmetry gate's subject
(``IRREDUCIBLE`` / ``PENDING_SYMMETRY``), not this one's. This gate asks only whether the
name still answers at all.

**Its exemptions carry arguments.** Both ledgers below follow ``IRREDUCIBLE``'s rule: every
entry states the argument, and "we did not port it" is not one.

What the fixture is *for*, since it has now been shrunk once
------------------------------------------------------------
``premerge_phase2_surface.json`` is a photograph of the wire at ``cf87774``, kept so that a
*regeneration* cannot quietly drop a name — the projector emits a smaller table than the six
hand-written files did, and nothing in the diff would say which name went. It is not a
promise that the product may never retire a command. Those are different claims, and only
the first is mechanical: a name that vanishes because a projector missed it leaves no
record anywhere, while a name that is retired on purpose leaves a commit that argues for it.

``flowmap`` and ``gas-tracker`` were removed from the fixture in the commit that deleted the
PyQt6 desktop layer. Both were ``QApplication`` launchers, both are gone from the tree, and
both are gone from ``_INFRASTRUCTURE`` and ``_INFRASTRUCTURE_AS_SHIPPED`` below in the same
edit — which is the point: an entry cannot leave one of these three places without leaving
all three, so shrinking the fixture is a four-file diff and not a line nobody reads. The
counts in :func:`test_the_frozen_surface_is_the_size_it_should_be` moved with it, which is
the assertion that makes a *fifth* deletion someone tries to sneak past fail loudly.
"""

