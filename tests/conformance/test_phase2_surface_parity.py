def test_no_wire_name_disappeared() -> None:
    """Every command, route and tool a user could call still answers.

    This is the assertion the deletion is not allowed to proceed without. The three surfaces
    are being regenerated from a registry that today holds two capabilities; the claim that
    the projection covers what six hand-written files covered is exactly the kind of
    superset claim Phase 1 made seven times and got wrong seven times.
    """
    served = _served()
    lost = sorted(
        {
            f"{fork}.{kind} {raw!r} → {name}"
            for fork, kind, raw, name, _params in _frozen_entries()
            if name not in _INFRASTRUCTURE and name not in served[kind]
        }
    )
    assert not lost, (
        f"{len(lost)} wire names that were callable before Phase 2 and are callable nowhere "
        f"now: {lost}. Serve them: a registry entry, or an `aliases` entry for a retired "
        "spelling. _INFRASTRUCTURE is not the remedy for this failure — it records that a "
        "name was *never* a capability, which is a claim about the past, and offering it "
        "here is how an exit review deleted `catalog-dates` and left all 689 conformance "
        "tests green. Adding a name to it now also fails "
        "test_the_infrastructure_list_cannot_grow_to_excuse_a_deleted_capability, which is "
        "the test to read before deciding this name was never a capability."
    )


def test_no_wire_parameter_disappeared() -> None:
    """A command that survives with half its options is a capability that half disappeared.

    The name is the coarse check; this is the one that catches a projection that kept
    `slippage` but dropped `size_unit`, which is the shape the Phase 1 losses actually had —
    the entry point still existed, it just answered with less.
    """
    served = _served()
    lost: list[str] = []
    for fork, kind, raw, name, params in _frozen_entries():
        if name in _INFRASTRUCTURE or name not in served[kind]:
            continue
        for param in params:
            canonical = _canonical_param(name, param)
            if canonical in _AMBIENT_PARAMETERS or (name, canonical) in _PARAM_BECAME_A_CAPABILITY:
                continue
            if canonical not in served[kind][name]:
                lost.append(f"{fork}.{kind} {raw!r} {param!r} → {name}.{canonical}")
    assert not lost, (
        f"{len(lost)} parameters accepted before Phase 2 and accepted nowhere now: "
        f"{sorted(lost)}. Either carry them onto the capability's params struct or add a "
        "justified entry to _PARAM_RENAMES, _PARAM_BECAME_A_CAPABILITY or "
        "_AMBIENT_PARAMETERS."
    )


def test_a_parameter_that_moved_landed_somewhere_reachable() -> None:
    """``_PARAM_BECAME_A_CAPABILITY`` must name a capability that is actually served.

    Without this the ledger would be an exemption list wearing a redirect: "it moved" is
    only a defence if the place it moved to answers. Every entry names a capability, and
    every one of those has to be reachable on the same surface kind the parameter was frozen
    on — which is the property the per-kind resolution above exists to keep.
    """
    served = _served()
    frozen_kinds: dict[str, set[str]] = {}
    for _fork, kind, _raw, name, params in _frozen_entries():
        for param in params:
            frozen_kinds.setdefault(f"{name}.{_canonical_param(name, param)}", set()).add(kind)

    stale: list[str] = []
    for (name, param), (target, why) in _PARAM_BECAME_A_CAPABILITY.items():
        entry = f"_PARAM_BECAME_A_CAPABILITY[{name!r}, {param!r}]"
        assert why.strip(), f"the move of {name}.{param} carries no justification"
        kinds = frozen_kinds.get(f"{name}.{param}")
        if not kinds:
            stale.append(f"{entry}: no surface ever accepted that parameter on {name}")
            continue
        for kind in kinds:
            if target not in served[kind]:
                stale.append(f"{entry} → {target}: not served on the {kind} surface")
    assert not stale, f"parameters recorded as moved with nowhere to have moved to: {stale}"


