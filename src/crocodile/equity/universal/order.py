def _midnight_ns(day: date) -> int:
    """UTC epoch nanoseconds of 00:00 UTC on ``day``."""
    return (day - _EPOCH_DATE).days * NS_PER_DAY


def _session_of(source_ts: int) -> date:
    """The UTC date a daily bar's ``source_ts`` stamps: its session date."""
    return _EPOCH_DATE + timedelta(days=source_ts // NS_PER_DAY)


def _epoch_ns(moment: datetime) -> int:
    delta = moment.astimezone(UTC) - _EPOCH_UTC
    return (delta.days * 86_400 + delta.seconds) * _NS_PER_SECOND + delta.microseconds * 1_000


def _identify(listing: Listing | str) -> tuple[str, str]:
    """The ``(symbol, mic)`` of a listing. A bare US ticker has no MIC and is refused."""
    if isinstance(listing, Listing):
        return listing.symbol, listing.mic
    _, mic = parse_listing_symbol(listing)
    if mic is None:
        raise ValueError(
            "resolve_daily_bars needs the listing's MIC; pass a Listing for a US bare ticker"
        )
    return listing, mic


def _priority(
    sources: tuple[str, ...] | None, order: SourceOrder, mic: str, present: Iterable[str]
) -> list[str]:
    if sources is not None:
        return list(sources)
    ranked = list(order.order_for(mic, "ohlcv"))
    ranked_set = set(ranked)
    return ranked + [name for name in sorted(set(present)) if name not in ranked_set]


def resolve_daily_bars(
    listing: Listing | str,
    start: date,
    end: date,
    *,
    catalog: Catalog,
    order: SourceOrder | None = None,
    sources: Sequence[str] | None = None,
) -> pl.DataFrame:
    """One daily bar per session date in ``[start, end]``, from the best-ranked source that has it.

    Filters on ``source_ts`` (the session date, stamped at UTC midnight), never on ``local_ts``.
    Within one source a session date keeps its latest capture. Columns are the lake's own
    ``ohlcv`` columns, unchanged, so ``currency`` and ``price_scale`` stay per row.
    """
    symbol, mic = _identify(listing)
    if start > end:
        raise ValueError(f"start {start.isoformat()} is after end {end.isoformat()}")
    if "ohlcv" not in catalog.list_channels():
        return pl.DataFrame()

    wanted: tuple[str, ...] | None = None
    params: list[object] = [
        symbol,
        DAILY_INTERVAL,
        _midnight_ns(start),
        _midnight_ns(end + timedelta(days=1)),
    ]
    sql = (
        'SELECT * FROM "ohlcv" WHERE symbol = ? AND "interval" = ? '
        "AND source_ts >= ? AND source_ts < ?"
    )
    if sources is not None:
        wanted = _unique(sources)
        if not wanted:
            return pl.DataFrame()
        sql += " AND source IN (" + ", ".join("?" for _ in wanted) + ")"
        params.extend(wanted)
    frame = catalog.query(sql, params=params)
    if frame.height == 0:
        return frame

    frame = frame.with_columns((pl.col("source_ts") // NS_PER_DAY).alias("_session_day"))
    frame = frame.sort(["source", "_session_day", "local_ts"]).unique(
        subset=["source", "_session_day"], keep="last", maintain_order=True
    )
    active = order if order is not None else source_order()
    priority = _priority(wanted, active, mic, frame["source"].to_list())
    resolved = CoverageResolver(
        priority,
        timestamp_col="_session_day",
        provider_col="source",
        symbol_col="symbol",
    ).resolve_df(frame, strategy="priority")
    return resolved.drop("_session_day").sort("source_ts")


def _close_ns(calendar: ExchangeCalendar, session: date) -> int:
    """The instant a session's close is stamped at.

    When the calendar cannot place the close (outside its window, or a day it does not know as
    a session) the stamp is the last nanosecond of the UTC day. That is never earlier than any
    real exchange's close on that local date, so it cannot be lookahead.
    """
    try:
        return _epoch_ns(calendar.session_close_utc(session))
    except (CalendarRangeError, NotASessionError):
        return _midnight_ns(session + timedelta(days=1)) - 1


def listing_close_leg(catalog: Catalog, symbol: str, start_ns: int, end_ns: int) -> pl.DataFrame:
    """``[local_ts, price]`` for a listing symbol: one close per session, at the session close.

    The ruling is that a listing's ``ohlcv`` leg is selected by session date and stamped at the
    session's close instant, not at capture time. Prices stay in the stored unit. The window
    ``[start_ns, end_ns]`` is applied to the stamped instant, as every other ``price_leg`` arm
    applies it to ``local_ts``.
    """
    # Lazy: the calendar is patched in tests, and the calendar module is cheap to leave unloaded.
    from crocodile.core.markets.calendar import calendar_for

    start_day = _EPOCH_DATE + timedelta(days=start_ns // NS_PER_DAY)
    end_day = _EPOCH_DATE + timedelta(days=end_ns // NS_PER_DAY)
    if start_day > end_day:
        return pl.DataFrame()
    frame = resolve_daily_bars(symbol, start_day, end_day, catalog=catalog)
    if frame.height == 0:
        return pl.DataFrame()
    _, mic = parse_listing_symbol(symbol)
    if mic is None:
        raise ValueError(f"{symbol!r} is not a listing symbol")
    calendar = calendar_for(mic)
    stamps: list[int] = []
    prices: list[float | None] = []
    for source_ts, close in zip(
        frame["source_ts"].to_list(), frame["close"].to_list(), strict=True
    ):
        session = _session_of(int(source_ts))
        stamps.append(_close_ns(calendar, session))
        prices.append(None if close is None else float(close))
    leg = pl.DataFrame(
        {"local_ts": stamps, "price": prices},
        schema={"local_ts": pl.Int64, "price": pl.Float64},
    )
    return (
        leg.filter(
            pl.col("price").is_not_null()
            & (pl.col("price") > 0.0)
            & pl.col("local_ts").is_between(start_ns, end_ns, closed="both")
        )
        .unique(subset=["local_ts"], keep="last", maintain_order=False)
        .sort("local_ts")
    )
