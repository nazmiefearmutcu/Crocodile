"""Per-market source order for universal equity reads (spec 3.10d, read half of section 2).

Every source keeps writing into its own ``source=`` partition and nobody overwrites anybody.
This module declares, as versioned data, which sources answer each ``(MIC, channel)`` and in
which order. The table lives in ``data/source_order.csv``, generated by
``scripts/build_source_order.py`` from the live registries, and validated against them.

Reading a daily bar means picking one bar per session date from the highest-ranked source that
has that date, through :class:`crocodile.core.coverage.resolver.CoverageResolver`. That is
:func:`resolve_daily_bars`. :func:`listing_close_leg` is its one consumer on the equity read
path: the ``ohlcv`` arm of ``price_leg`` for ``{local}@{MIC}`` listing symbols.

Rules of the generated table (see :func:`build_default_rows`):

* US natives (``US_NATIVE_ORDER``) lead the US rows; natives never appear in a non-US row,
  because a native takes raw symbols and never a ``X@MIC`` canonical symbol.
* Non-US ``ohlcv`` rows list ``yahoo_chart`` before ``tradingview``.
* ``instrument`` rows list the directory sources, then ``tradingview``, then ``yahoo_chart``.
  ``yahoo_chart`` declares no ``instrument`` channel, so it is filtered out of those rows.
* Non-US ``corp_action`` rows list only universal sources.

The table is data an operator may later edit. Editing it by hand is refused by the build
script's ``--check`` mode until the table is regenerated or the registries agree with it.

Nothing here runs at import time. The provider factory is imported lazily, because sources
live under this package and the factory imports them.

The module is ASCII-only, as every new file in ``equity/universal`` must be.
"""

from __future__ import annotations

import csv
import functools
import importlib.resources
import io
from collections.abc import Collection, Iterable, Mapping, Sequence
from dataclasses import dataclass
from datetime import UTC, date, datetime, timedelta
