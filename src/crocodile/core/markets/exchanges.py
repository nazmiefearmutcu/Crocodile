"""The exchange allow-list: ``exchanges.csv`` and ``ExchangeRegistry``.

``exchanges.csv`` is generated by ``scripts/build_markets_reference.py``. It lists
the operating MICs the platform will collect from, with the civil time zone,
primary currency, quote scale, weekend, regular close and research tier of each.
A MIC that is not on this list is refused even when ISO 10383 calls it active:
``get`` raises ``UnknownMarketError`` for it.

``get`` is exact. ``resolve`` accepts a segment MIC and maps it to its operating
MIC first, so ``resolve("XTKS")`` returns the ``XJPX`` row while ``get("XTKS")``
refuses with a pointer to ``XJPX``.
"""

from __future__ import annotations

import functools
import re
from collections.abc import Iterable, Mapping
from datetime import date, time
from types import MappingProxyType
from typing import Final
from zoneinfo import ZoneInfo

import msgspec

from crocodile.core.markets._data import read_csv
from crocodile.core.markets.currency import require_currency
from crocodile.core.markets.errors import (
    ReferenceDataError,
    UnknownCurrencyError,
    UnknownMarketError,
)
from crocodile.core.markets.mic import MicRegistry, _packaged_index

__all__ = [
    "EXCHANGES_FILE",
    "EXCHANGE_COLUMNS",
    "WEEKDAY_TOKENS",
    "ExchangeInfo",
    "ExchangeRegistry",
    "format_weekend",
    "parse_exchange_row",
    "parse_weekend",
]

EXCHANGES_FILE: Final = "exchanges.csv"
EXCHANGE_COLUMNS: Final = (
    "mic",
    "name",
    "country",
    "timezone",
    "currency",
    "quote_scale",
    "weekend",
    "close_local",
    "xcal_code",
    "tier_research",
    "sanctioned",
    "notes",
)
WEEKDAY_TOKENS: Final = ("MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN")
_TIERS: Final = frozenset({"A", "B", "C", "D"})
_MIC_RE: Final = re.compile(r"[A-Z0-9]{4}")
_COUNTRY_RE: Final = re.compile(r"[A-Z]{2}")
_CLOSE_RE: Final = re.compile(r"(\d{2}):(\d{2})")


class ExchangeInfo(msgspec.Struct, frozen=True, kw_only=True):
    """One allow-listed operating MIC with its trading-calendar facts."""

    mic: str
    name: str
    country: str
    tz: ZoneInfo
    currency: str
    quote_scale: int
    weekend: frozenset[int]
    close_local: time | None
    xcal_code: str | None
    tier_research: str
    sanctioned: bool
    notes: str = ""

    def is_weekend(self, d: date) -> bool:
        """True when the exchange does not trade on the weekday of ``d``."""
        return d.weekday() in self.weekend


def parse_weekend(raw: str) -> frozenset[int]:
    """Parse ``"SAT,SUN"`` into ``date.weekday()`` numbers. Refuses bad or 7-day input."""
    if not raw:
        raise ValueError("weekend is empty")
    tokens = raw.split(",")
    unknown = [token for token in tokens if token not in WEEKDAY_TOKENS]
    if unknown:
        raise ValueError(f"unknown weekday token {unknown[0]!r} in {raw!r}")
    if len(set(tokens)) != len(tokens):
        raise ValueError(f"duplicate weekday in {raw!r}")
    days = frozenset(WEEKDAY_TOKENS.index(token) for token in tokens)
    if len(days) >= 7:
        raise ValueError(f"a weekend of {len(days)} days is refused: {raw!r}")
    return days


def format_weekend(days: Iterable[int]) -> str:
    """Render weekday numbers Monday-first, for example ``{4, 5}`` as ``"FRI,SAT"``."""
    values = list(days)
    if not values:
        raise ValueError("weekend is empty")
    if len(set(values)) != len(values):
        raise ValueError(f"duplicate weekday in {values!r}")
    if any(not 0 <= day <= 6 for day in values):
        raise ValueError(f"weekday numbers must be 0 to 6: {values!r}")
    if len(values) >= 7:
        raise ValueError("a weekend of 7 days is refused")
    return ",".join(WEEKDAY_TOKENS[day] for day in sorted(values))


def parse_exchange_row(row: Mapping[str, str], line: int) -> ExchangeInfo:
    """Validate one ``exchanges.csv`` row. Any violation raises ``ReferenceDataError``."""

    def bad(detail: str) -> ReferenceDataError:
        return ReferenceDataError(EXCHANGES_FILE, f"line {line}: {detail}")

    mic = row["mic"]
    if not _MIC_RE.fullmatch(mic):
        raise bad(f"mic {mic!r} is not four upper-case characters")
    country = row["country"]
    if not _COUNTRY_RE.fullmatch(country):
        raise bad(f"country {country!r} is not an ISO 3166 alpha-2 code")
    try:
        tz = ZoneInfo(row["timezone"])
    except (KeyError, ValueError) as exc:
        raise bad(f"timezone {row['timezone']!r} does not load") from exc
    try:
        currency = require_currency(row["currency"])
    except UnknownCurrencyError as exc:
        raise bad(f"currency {row['currency']!r} is not in ISO 4217") from exc
    if row["quote_scale"] not in {"0", "2"}:
        raise bad(f"quote_scale {row['quote_scale']!r} must be 0 or 2")
    try:
        weekend = parse_weekend(row["weekend"])
    except ValueError as exc:
        raise bad(str(exc)) from exc
    if format_weekend(weekend) != row["weekend"]:
        raise bad(f"weekend {row['weekend']!r} is not in Monday-first canonical order")
    close_local: time | None = None
    if row["close_local"]:
        match = _CLOSE_RE.fullmatch(row["close_local"])
        if match is None:
            raise bad(f"close_local {row['close_local']!r} is not HH:MM")
        try:
            close_local = time(int(match.group(1)), int(match.group(2)))
        except ValueError as exc:
            raise bad(f"close_local {row['close_local']!r} is out of range") from exc
    if row["tier_research"] not in _TIERS:
        raise bad(f"tier_research {row['tier_research']!r} must be A, B, C or D")
    if row["sanctioned"] not in {"true", "false"}:
        raise bad(f"sanctioned {row['sanctioned']!r} must be true or false")
    return ExchangeInfo(
        mic=mic,
        name=row["name"],
        country=country,
        tz=tz,
        currency=currency,
        quote_scale=int(row["quote_scale"]),
        weekend=weekend,
        close_local=close_local,
        xcal_code=row["xcal_code"] or None,
        tier_research=row["tier_research"],
        sanctioned=row["sanctioned"] == "true",
        notes=row["notes"],
    )


@functools.cache
def _packaged_exchange_index() -> Mapping[str, ExchangeInfo]:
    table: dict[str, ExchangeInfo] = {}
    for line, row in enumerate(read_csv(EXCHANGES_FILE, EXCHANGE_COLUMNS), start=2):
        info = parse_exchange_row(row, line)
        if info.mic in table:
            raise ReferenceDataError(EXCHANGES_FILE, f"line {line}: duplicate mic {info.mic}")
        table[info.mic] = info
    return MappingProxyType(table)


def _index(rows: Iterable[ExchangeInfo]) -> Mapping[str, ExchangeInfo]:
    table: dict[str, ExchangeInfo] = {}
    for info in rows:
        if info.mic in table:
            raise ReferenceDataError(EXCHANGES_FILE, f"duplicate mic {info.mic}")
        table[info.mic] = info
    return MappingProxyType(table)


class ExchangeRegistry:
    """The allow-list of operating MICs, with exact and segment-tolerant lookups."""

    def __init__(self, rows: Iterable[ExchangeInfo] | None = None) -> None:
        self._injected: Mapping[str, ExchangeInfo] | None = None if rows is None else _index(rows)

    def _table(self) -> Mapping[str, ExchangeInfo]:
        return self._injected if self._injected is not None else _packaged_exchange_index()

    def get(self, mic: str) -> ExchangeInfo:
        """Return the allow-listed row for an exact operating ``mic``."""
        info = self._table().get(mic)
        if info is not None:
            return info
        detail = ""
        known = _packaged_index().get(mic)
        if known is not None and known.is_segment:
            detail = f"segment of {known.operating_mic}; use the operating MIC"
        elif known is not None and known.is_active:
            detail = "not in the exchanges.csv allow-list"
        raise UnknownMarketError(mic, detail)

    def resolve(self, mic: str, *, mics: MicRegistry | None = None) -> ExchangeInfo:
        """Map a segment or operating ``mic`` to its operating row, then look it up."""
        registry = mics if mics is not None else MicRegistry()
        return self.get(registry.operating(mic))

    def by_country(self, iso2: str) -> tuple[ExchangeInfo, ...]:
        """Every allow-listed exchange of an ISO 3166 alpha-2 country, sorted by MIC."""
        if not _COUNTRY_RE.fullmatch(iso2):
            raise ValueError(f"country must be two upper-case letters, got {iso2!r}")
        rows = [info for info in self._table().values() if info.country == iso2]
        return tuple(sorted(rows, key=lambda info: info.mic))

    def all(self) -> tuple[ExchangeInfo, ...]:
        """Every row, sorted by MIC."""
        table = self._table()
        return tuple(table[mic] for mic in sorted(table))

    def __contains__(self, mic: object) -> bool:
        return isinstance(mic, str) and mic in self._table()

    def __len__(self) -> int:
        return len(self._table())
